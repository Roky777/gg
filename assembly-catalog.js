/** Shuffle bags guarantee every picture appears before any picture repeats. */
export class AssemblyDeck{
 constructor(items=ASSEMBLY_PICTURES,random=Math.random){this.items=items;this.random=random;this.bag=[];this.last=null;}
 next(){if(!this.bag.length){this.bag=[...this.items];for(let i=this.bag.length-1;i>0;i--){const j=Math.floor(this.random()*(i+1));[this.bag[i],this.bag[j]]=[this.bag[j],this.bag[i]];}if(this.bag.length>1&&this.bag.at(-1).id===this.last)[this.bag[0],this.bag[this.bag.length-1]]=[this.bag.at(-1),this.bag[0]];}const item=this.bag.pop();this.last=item.id;return item;}
}
