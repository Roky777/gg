export const solved=order=>order.length===3&&order.every((piece,slot)=>piece===slot);
export function swap(order,a,b){if(![a,b].every(i=>Number.isInteger(i)&&i>=0&&i<3))throw new RangeError('Invalid slot');const next=order.slice();[next[a],next[b]]=[next[b],next[a]];return next;}
export function scramble(random=Math.random){const choices=[[1,2,0],[2,0,1],[2,1,0],[1,0,2],[0,2,1]];return choices[Math.min(4,Math.floor(random()*5))].slice();}
export function slotAt(x,y,rect,axis){const value=axis==='vertical'?(x-rect.left)/rect.width:(y-rect.top)/rect.height;return Math.max(0,Math.min(2,Math.floor(value*3)));}

export function fitPicture(iw,ih,bw,bh){if([iw,ih,bw,bh].some(n=>!Number.isFinite(n)||n<=0))throw new RangeError('Invalid image size');const scale=Math.max(bw/iw,bh/ih);return {width:iw*scale,height:ih*scale,x:(bw-iw*scale)/2,y:(bh-ih*scale)/2,scale};}

export const correctPieces=order=>order.reduce((n,piece,slot)=>n+Number(piece===slot),0);
export function swapFeedback(before,after){const change=correctPieces(after)-correctPieces(before);return change>0?'yes':change<0?'no':null;}

/** One full shuffled cycle, with no immediate repeat at a cycle boundary. */
export function shuffledDeck(length,previous=-1,random=Math.random){
 const deck=Array.from({length},(_,i)=>i);for(let i=length-1;i>0;i--){const j=Math.floor(random()*(i+1));[deck[i],deck[j]]=[deck[j],deck[i]];}
 if(length>1&&deck[0]===previous)[deck[0],deck[1]]=[deck[1],deck[0]];return deck;
}
